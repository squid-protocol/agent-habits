static const int *PST_MID[7] = {NULL, PST_PAWN, PST_KNIGHT, PST_BISHOP, PST_ROOK, PST_QUEEN, PST_KING_MID};

/* Tapered evaluation: middlegame and endgame scores blended by remaining material. */
int evaluate(const Position *p) {
    int mg = 0, eg = 0, phase = 0;
    for (int r = 0; r < 8; r++)
        for (int f = 0; f < 8; f++) {
            const int pc = p->board[SQ(f, r)];
            if (!pc) continue;
            const int color = COLOR_OF(pc), type = TYPE_OF(pc);
            const int idx = color == WHITE ? (7 - r) * 8 + f : r * 8 + f;
            const int vm = PIECE_VALUE[type] + PST_MID[type][idx];
            const int ve = PIECE_VALUE[type] +
                           (type == KING ? PST_KING_END[idx] : PST_MID[type][idx]);
            const int sign = color == WHITE ? 1 : -1;
            mg += sign * vm;
            eg += sign * ve;
            phase += PHASE_WEIGHT[type];
        }
    if (phase > 24) phase = 24;
    const int score = (mg * phase + eg * (24 - phase)) / 24;
    return p->side == WHITE ? score : -score;
}
