const MG_PST: [&[i32; 64]; 6] = [&PAWN_PST, &KNIGHT_PST, &BISHOP_PST, &ROOK_PST, &QUEEN_PST, &KING_MG_PST];

/// Score in centipawns from the point of view of the side to move.
pub fn evaluate(pos: &Position) -> i32 {
    let mut mg = [0i32; 2];
    let mut eg = [0i32; 2];
    let mut phase = 0;
    for color in [WHITE, BLACK] {
        for kind in 0..6 {
            let mut bb = pos.pieces[color * 6 + kind];
            while bb != 0 {
                let sq = bb.trailing_zeros() as usize;
                bb &= bb - 1;
                let idx = if color == WHITE { sq ^ 56 } else { sq };
                mg[color] += MATERIAL_MG[kind] + MG_PST[kind][idx];
                eg[color] += MATERIAL_EG[kind]
                    + if kind == KING { KING_EG_PST[idx] } else { MG_PST[kind][idx] };
                phase += PHASE_WEIGHT[kind];
            }
        }
    }
    let phase = phase.min(24);
    let score = ((mg[WHITE] - mg[BLACK]) * phase + (eg[WHITE] - eg[BLACK]) * (24 - phase)) / 24;
    if pos.stm == WHITE {
        score
    } else {
        -score
    }
}
