const PST: [[i32; 64]; 5] = [PAWN_PST, KNIGHT_PST, BISHOP_PST, ROOK_PST, QUEEN_PST];

/// Score in centipawns from the point of view of the side to move.
pub fn evaluate(pos: &Position) -> i32 {
    let mut mg = [0i32; 2];
    let mut eg = [0i32; 2];
    let mut phase = 0;
    for color in [WHITE, BLACK] {
        for pt in 0..6 {
            let mut bb = pos.bb[color * 6 + pt];
            while bb != 0 {
                let sq = pop_lsb(&mut bb);
                let idx = if color == WHITE { sq ^ 56 } else { sq };
                let (m, e) = if pt == KING {
                    (KING_MG_PST[idx], KING_EG_PST[idx])
                } else {
                    (PST[pt][idx], PST[pt][idx])
                };
                mg[color] += MG_VAL[pt] + m;
                eg[color] += EG_VAL[pt] + e;
                phase += PHASE[pt];
            }
        }
    }
    let ph = phase.min(24);
    let white = (mg[WHITE] - mg[BLACK]) * ph + (eg[WHITE] - eg[BLACK]) * (24 - ph);
    let score = white / 24;
    if pos.side == WHITE {
        score
    } else {
        -score
    }
}
